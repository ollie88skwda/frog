const norm = (s: string) => s.toLowerCase();

/** Simple substring search over brand + model + category. */
export function searchCatalog(query: string, limit = 20): CatalogMachine[] {
  const q = norm(query.trim());
  if (!q) return [];
  const terms = q.split(/\s+/);
  const results: CatalogMachine[] = [];
  for (const m of MACHINE_CATALOG) {
    const hay = norm(`${m.brand} ${m.model} ${m.category.replace(/-/g, " ")}`);
    if (terms.every((t) => hay.includes(t))) {
      results.push(m);
      if (results.length >= limit) break;
    }
  }
  return results;
}
